"""Build the canary papers (eval set A) and keep config/canary_allowlist.yaml in sync.

Each canary is `eval/canaries/<name>/{paper.tex,experiment.py,truth.yaml}`. What the pipeline
ingests is the canary's arXiv-style e-print: `paper.tex` (LF line endings) gzipped with stored
blocks and a zero mtime, so the bytes, and the sha256 INGESTING records for the run, are the
same on every platform. Those hashes are the allowlist LocalTrustedExecutor checks.

    uv run python -m eval.canaries.build            # rewrite config/canary_allowlist.yaml
    uv run python -m eval.canaries.build --check    # exit 1 if the allowlist is stale
    uv run python -m eval.canaries.build --measure  # rerun every experiment, print the verdicts
    uv run python -m eval.canaries.build --pdf DIR  # PDFs with tectonic (optional, network)
"""

import argparse
import functools
import hashlib
import importlib.util
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Self

import yaml
from pydantic import BaseModel, ConfigDict, Field, model_validator

from app.domain.models import (
    Claim,
    ClaimType,
    Measurements,
    Scale,
    Verdict,
    VerdictKind,
)
from app.execution.local_trusted import load_canaries
from app.ingestion.canaries import gzip_stored
from app.verdict.config import load_verdict_config
from app.verdict.engine import decide

CANARIES_DIR = Path(__file__).resolve().parent
ROOT = CANARIES_DIR.parents[1]
ALLOWLIST = ROOT / "config" / "canary_allowlist.yaml"
CANARY_ARXIV_ID = r"^0000\.\d{5}$"  # a subset of app.ingestion.arxiv.ARXIV_ID
_GZIP_HEADER = b"\x1f\x8b\x08\x00\x00\x00\x00\x00\x00\xff"  # no flags, mtime 0, OS unknown
_ALLOWLIST_HEADER = """\
# SHA-256 of canary papers (eval set A). LocalTrustedExecutor runs ONLY these, ONLY with
# P2P_ENV=dev. Generated by `uv run python -m eval.canaries.build` (A-29); do not edit by hand.
# Each hash is the canary's arXiv-style e-print (gzipped paper.tex), the bytes INGESTING hashes.
"""


class TruthClaim(Claim):
    planted: bool  # true: a false claim planted on purpose (inflated or reversed)


class Truth(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    arxiv_id: str = Field(pattern=CANARY_ARXIV_ID)  # month 00: never a real arXiv paper
    title: str = Field(min_length=1)
    seeds: list[int] = Field(min_length=3)
    verdicts: dict[str, VerdictKind]  # {claim_id: expected_verdict} under config/verdict.yaml
    claims: list[TruthClaim] = Field(min_length=1)

    @model_validator(mode="after")
    def _one_verdict_per_claim(self) -> Self:
        if set(self.verdicts) != {c.id for c in self.claims}:
            raise ValueError("verdicts must name every claim exactly once")
        return self


@dataclass(frozen=True)
class Canary:
    name: str
    path: Path
    truth: Truth

    @property
    def paper(self) -> Path:
        return self.path / "paper.tex"

    @property
    def experiment(self) -> Path:
        return self.path / "experiment.py"


@dataclass(frozen=True)
class Measured:
    per_seed: dict[int, dict[str, float]]  # seed -> metrics.json
    verdicts: dict[str, Verdict]


def discover(root: Path = CANARIES_DIR) -> list[Canary]:
    return [
        Canary(
            name=truth.parent.name,
            path=truth.parent,
            truth=Truth.model_validate(yaml.safe_load(truth.read_text(encoding="utf-8"))),
        )
        for truth in sorted(root.glob("*/truth.yaml"))
    ]


def get(name: str) -> Canary:
    return next(c for c in discover() if c.name == name)


def source_bytes(canary: Canary) -> bytes:
    return gzip_stored(canary.paper.read_bytes().replace(b"\r\n", b"\n"))


def source_sha256(canary: Canary) -> str:
    return hashlib.sha256(source_bytes(canary)).hexdigest()


def render_allowlist(canaries: list[Canary]) -> str:
    lines = [f"  - {source_sha256(c)}  # {c.truth.arxiv_id} {c.name}" for c in canaries]
    return _ALLOWLIST_HEADER + "papers:\n" + "".join(f"{line}\n" for line in lines)


def write_allowlist(path: Path = ALLOWLIST) -> None:
    path.write_text(render_allowlist(discover()), encoding="utf-8", newline="\n")


def check(path: Path = ALLOWLIST) -> list[str]:
    """Problems with the allowlist at `path`; empty when it lists exactly the canaries."""
    listed = load_canaries(path)
    wanted = {source_sha256(c): c.name for c in discover()}
    problems = [
        f"missing: {name} ({digest})" for digest, name in wanted.items() if digest not in listed
    ]
    problems += [f"unknown hash: {digest}" for digest in sorted(listed - wanted.keys())]
    return problems


def _load_experiment(canary: Canary) -> object:
    spec = importlib.util.spec_from_file_location(
        f"canary_{canary.name.replace('-', '_')}", canary.experiment
    )
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {canary.experiment}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@functools.cache
def _measure(name: str) -> Measured:
    canary = get(name)
    run = getattr(_load_experiment(canary), "run")  # noqa: B009 (module loaded from a path)
    per_seed = {seed: run(seed, smoke=False) for seed in canary.truth.seeds}
    cfg = load_verdict_config()
    verdicts: dict[str, Verdict] = {}
    for claim in canary.truth.claims:
        relative = claim.claim_type == ClaimType.RELATIVE
        measurements = Measurements(
            scale=Scale.FULL,
            per_seed=[per_seed[s][claim.metric] for s in canary.truth.seeds],
            baseline_per_seed=(
                [per_seed[s][f"baseline/{claim.metric}"] for s in canary.truth.seeds]
                if relative
                else None
            ),
        )
        plain = Claim.model_validate(claim.model_dump(exclude={"planted"}))
        verdicts[claim.id] = decide(plain, measurements, cfg)
    return Measured(per_seed=per_seed, verdicts=verdicts)


def measure(canary: Canary) -> Measured:
    """Run the experiment at full scale for every truth seed (in process) and decide()."""
    return _measure(canary.name)


def compile_pdf(canary: Canary, outdir: Path, tectonic: str) -> Path:
    """Compile paper.tex with tectonic (untrusted mode, no shell escape) in a scratch directory.
    The PDF is for reading only. tectonic downloads its TeX bundle over the network on first use."""
    outdir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as scratch:
        tex = Path(scratch) / "paper.tex"
        shutil.copyfile(canary.paper, tex)
        subprocess.run(  # noqa: S603 (fixed argv, no shell)
            [tectonic, "--untrusted", str(tex)], cwd=scratch, check=True
        )
        target = outdir / f"{canary.name}.pdf"
        shutil.copyfile(Path(scratch) / "paper.pdf", target)
    return target


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="exit 1 if the allowlist is stale")
    mode.add_argument(
        "--measure", action="store_true", help="rerun the experiments, print verdicts"
    )
    mode.add_argument("--pdf", type=Path, metavar="DIR", help="compile the PDFs with tectonic")
    args = parser.parse_args(argv)
    if args.check:
        problems = check()
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1 if problems else 0
    if args.measure:
        wrong = 0
        for canary in discover():
            measured = measure(canary)
            for claim in canary.truth.claims:
                verdict = measured.verdicts[claim.id]
                expected = canary.truth.verdicts[claim.id]
                wrong += verdict.kind != expected
                values = [m[claim.metric] for m in measured.per_seed.values()]
                print(
                    f"{canary.name:20s} {claim.id} planted={claim.planted!s:5s} "
                    f"{verdict.kind:16s} expected={expected:16s} mean={verdict.mean:.4f} "
                    f"std={verdict.std:.4f} {claim.metric}={[round(v, 4) for v in values]}"
                )
        return 1 if wrong else 0
    if args.pdf:
        tectonic = shutil.which("tectonic")
        if tectonic is None:
            print(
                "tectonic is not on PATH (https://tectonic-typesetting.github.io)", file=sys.stderr
            )
            return 1
        for canary in discover():
            print(compile_pdf(canary, args.pdf, tectonic))
        return 0
    write_allowlist()
    print(f"wrote {ALLOWLIST.relative_to(ROOT).as_posix()} ({len(discover())} canaries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
