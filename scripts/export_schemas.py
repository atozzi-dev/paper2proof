"""Generate schemas/events.schema.json from app.domain.events (deterministic output).

Usage: uv run python scripts/export_schemas.py [--stdout]   (--help for help)
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.domain.events import PAYLOAD_MODELS, EventEnvelope  # noqa: E402

OUT = ROOT / "schemas" / "events.schema.json"


def build() -> str:
    schema = EventEnvelope.model_json_schema(mode="serialization")
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$id"] = "https://paper2proof.dev/schemas/events.schema.json"
    schema["title"] = "p2p SSE event envelope (generated by scripts/export_schemas.py)"
    schema["x-event-types"] = {t.value: m.__name__ for t, m in PAYLOAD_MODELS.items()}
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--stdout", action="store_true", help="print instead of writing the file")
    args = parser.parse_args()
    text = build()
    if args.stdout:
        sys.stdout.write(text)
    else:
        OUT.write_bytes(text.encode("utf-8"))
        print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
