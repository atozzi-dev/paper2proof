"""Regenerate config/pypi_top500.txt from the public "top PyPI packages" dataset.

Usage: uv run python scripts/gen_pypi_top.py [--count 500]   (--help for help)
Source: https://hugovk.github.io/top-pypi-packages/ (BigQuery download counts, 30 days).
Network access; free; run it by hand and commit the result.
"""

import argparse
import json
import urllib.request
from pathlib import Path

SOURCE = "https://hugovk.github.io/top-pypi-packages/top-pypi-packages.min.json"
OUT = Path(__file__).resolve().parents[1] / "config" / "pypi_top500.txt"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--count", type=int, default=500)
    args = parser.parse_args()
    with urllib.request.urlopen(SOURCE, timeout=60) as response:
        data = json.load(response)
    names = [row["project"] for row in data["rows"][: args.count]]
    header = (
        "# Popular PyPI packages for the typosquat check (package policy rule 4).\n"
        f"# Generated by scripts/gen_pypi_top.py from {SOURCE}\n"
    )
    OUT.write_text(header + "\n".join(sorted(set(names))) + "\n", encoding="utf-8")
    print(f"wrote {len(names)} names to {OUT.relative_to(OUT.parents[1])}")


if __name__ == "__main__":
    main()
