"""Regenerate config/pypi_top500.txt: the most downloaded PyPI projects plus a curated ML list.

Usage: uv run python scripts/gen_pypi_top.py [--count 500] [--source URL_OR_FILE]  (--help)
Source: https://hugovk.github.io/top-pypi-packages/ (30-day download counts).
The download ranking alone misses ML staples (timm, jax and einops rank below 500) and would
make them look like typosquats of popular short names (timm is 2 edits from tqdm), so every
name in config/pypi_curated.txt is kept. The output depends only on the snapshot and the
curated list. Network access (free); run it by hand and commit the result.
"""

import argparse
import json
import re
import urllib.request
from collections.abc import Sequence
from pathlib import Path
from typing import Any

SOURCE = "https://hugovk.github.io/top-pypi-packages/top-pypi-packages.min.json"
CONFIG = Path(__file__).resolve().parents[1] / "config"
NAME = re.compile(r"^[A-Za-z0-9]([A-Za-z0-9._-]*[A-Za-z0-9])?$")  # PEP 508 project name


def normalize(name: str) -> str:
    """PEP 503, as app/execution/package_policy.py compares names."""
    return re.sub(r"[-_.]+", "-", name).lower()


def top_names(data: Any, count: int) -> list[str]:
    """The `count` most downloaded projects, normalized, ties broken by name."""
    rows = data.get("rows") if isinstance(data, dict) else None
    if not isinstance(rows, list):
        raise ValueError("the snapshot has no rows list")
    ranked: list[tuple[int, str]] = []
    for row in rows:
        project = row.get("project") if isinstance(row, dict) else None
        downloads = row.get("download_count") if isinstance(row, dict) else None
        if not isinstance(project, str) or not NAME.fullmatch(project):
            raise ValueError(f"bad project name in the snapshot: {str(project)[:80]!r}")
        if type(downloads) is not int:
            raise ValueError(f"bad download count for {project}")
        ranked.append((-downloads, normalize(project)))
    names: list[str] = []
    for _, name in sorted(ranked):
        if name not in names:
            names.append(name)
    if len(names) < count:
        raise ValueError(f"the snapshot has only {len(names)} projects, {count} requested")
    return names[:count]


def read_names(text: str) -> list[str]:
    """Names of a list file: one per line, `#` comments and blank lines skipped."""
    return [s for line in text.splitlines() if (s := line.strip()) and not s.startswith("#")]


def render(top: list[str], curated: list[str], data: Any, count: int) -> str:
    snapshot = " ".join(str(data.get("last_update", "unknown")).split())[:40]
    header = (
        "# Popular PyPI packages for the typosquat check (package policy rule 4).\n"
        "# Generated by scripts/gen_pypi_top.py: do not edit (add names to pypi_curated.txt).\n"
        f"# Top {count} of {SOURCE} (snapshot {snapshot}) + config/pypi_curated.txt\n"
    )
    names = sorted({*top, *(normalize(n) for n in curated)})
    return header + "\n".join(names) + "\n"


def _load(source: str) -> Any:
    if source.startswith("https://"):
        with urllib.request.urlopen(source, timeout=60) as response:  # noqa: S310 - https only
            return json.load(response)
    return json.loads(Path(source).read_text(encoding="utf-8"))


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--count", type=int, default=500)
    parser.add_argument("--source", default=SOURCE, help="https URL or a local JSON snapshot")
    parser.add_argument("--curated", type=Path, default=CONFIG / "pypi_curated.txt")
    parser.add_argument("--out", type=Path, default=CONFIG / "pypi_top500.txt")
    args = parser.parse_args(argv)
    data = _load(args.source)
    curated = read_names(args.curated.read_text(encoding="utf-8"))
    bad = [n for n in curated if not NAME.fullmatch(n)]
    if bad:
        raise SystemExit(f"bad names in {args.curated}: {bad[:5]}")
    text = render(top_names(data, args.count), curated, data, args.count)
    args.out.write_bytes(text.encode("utf-8"))  # LF on every platform
    print(f"wrote {len(read_names(text))} names to {args.out}")


if __name__ == "__main__":
    main()
