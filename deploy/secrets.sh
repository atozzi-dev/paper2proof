#!/usr/bin/env bash
# Load the control-plane secrets into the SecretStash (MysteryBox) secret p2p-secrets (H-04,
# architecture §9.2, docs/OPERATIONS.md "Rotate after judging"). Human only, with the nebius CLI
# logged in as a tenant admin and the Terraform state reachable: the sa-tfstate S3 key in
# AWS_ACCESS_KEY_ID / AWS_SECRET_ACCESS_KEY, and `terraform init` done in envs/prod and
# envs/prod-iam on this machine (as in H-04). It works from any directory.
#
# Usage: deploy/secrets.sh [--only KEY[,KEY...] | --replace-all]
#   no option      first load: every key that deploy/endpoint.sh maps (SECRET_VARS), plus the
#                  optional OBSERVABILITY_STATIC_KEY, in one new primary version. Refused when
#                  the secret already has a version.
#   --only         rotation: replace only these keys and keep the others from the current
#                  primary version. An S3 key ID and its secret always change together.
#   --replace-all  a first load over an existing version (new values for every key).
#
# Where each value comes from:
#   NEBIUS_API_KEY, TAVILY_API_KEY, OBSERVABILITY_STATIC_KEY   asked for, input hidden
#   ADMIN_TOKEN        asked for (paste one from the password manager: the default), or
#                      generated and shown once on the terminal (never on stdout)
#   SESSION_KEY        generated, never shown
#   *_S3_KEY_ID        terraform output s3_access_keys (envs/prod-iam)
#   *_S3_SECRET        the SecretStash secret those keys reference (MYSTERY_BOX delivery)
#   *_AUTH_KEY         a new authorized key of sa-api-runtime (in p2p-control) and of
#                      sa-job-launcher (in p2p-sandbox), generated by the CLI
# No value is passed on a command line or printed. The generated key files and the request
# for the new version exist only in a private temporary directory (in /dev/shm when it can
# be used), removed on every exit. Do not pipe this script through tee or a session logger.
#
# Environment: TERRAFORM (terraform), PY (python3), P2P_TF_ENVS (infra/terraform/envs of this
#   repository), P2P_KEY_EXPIRES_AT (2027-01-31T00:00:00Z: after judging; at least 30 days
#   ahead), P2P_TTY (/dev/tty: where a generated ADMIN_TOKEN is shown), P2P_ENV_FILE
#   (deploy/prod.env: with Nebius Tracing there, OBSERVABILITY_STATIC_KEY is required),
#   DRY_RUN=1 (read, ask, change nothing).
# ASSUMPTIONS to check on the first real run (H-04; `--help` of each command is free), then
# note the facts in docs/spikes/RESULTS.md:
#   - `nebius iam auth-public-key generate` takes --parent-id, --service-account-id, --output,
#     --output-format service-account-json and --expires-at, and writes the SDK credentials
#     JSON ({"subject-credentials": {"private-key", "kid", "iss", "sub", ...}});
#   - `nebius mysterybox secret-version create --file <path>` takes the whole request as JSON
#     ({metadata: {parent_id}, spec: {payload: [{key, string_value}], set_primary}});
#   - `mysterybox payload get --format json` lists entries as {key, string_value} objects;
#   - the secret of a MYSTERY_BOX access key is the only entry of its secret (or the entry whose
#     key contains "secret");
#   - the CLI does not echo request bodies on a validation error or into ~/.nebius logs;
#   - `payload get` on a secret without a version fails with a "not found" / "no primary
#     version" message (check the exact text, and that a permission error does not look so).
set +x # an inherited xtrace would print every value
set -euo pipefail

ROOT="$(CDPATH='' cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
TERRAFORM="${TERRAFORM:-terraform}"
PY="${PY:-python3}"
ENVS="${P2P_TF_ENVS:-$ROOT/infra/terraform/envs}"
EXPIRES="${P2P_KEY_EXPIRES_AT:-2027-01-31T00:00:00Z}"
TTY="${P2P_TTY:-/dev/tty}"
ENV_FILE="${P2P_ENV_FILE:-$ROOT/deploy/prod.env}" # read for the tracing setting
# The keys deploy/endpoint.sh maps from the secret (its SECRET_VARS; a test keeps them equal).
KEYS=(NEBIUS_API_KEY TAVILY_API_KEY SESSION_KEY ADMIN_TOKEN RUNTIME_S3_KEY_ID RUNTIME_S3_SECRET
  RUNTIME_AUTH_KEY JOB_LAUNCHER_AUTH_KEY JOB_LAUNCHER_S3_KEY_ID JOB_LAUNCHER_S3_SECRET)
OPTIONAL=(OBSERVABILITY_STATIC_KEY)
TF_HINT="(are AWS_ACCESS_KEY_ID/AWS_SECRET_ACCESS_KEY exported and terraform init done there?)"

die() { echo "secrets.sh: $*" >&2; exit 1; }
dry() { [ "${DRY_RUN:-}" = 1 ]; }
say() { echo "== $*"; }
is_key() { # is_key NAME: one of KEYS or OPTIONAL, matched exactly
  local key
  for key in "${KEYS[@]}" "${OPTIONAL[@]}"; do [ "$key" = "$1" ] && return 0; done
  return 1
}

# JSON, digests and tokens without jq. Secret values travel on stdin/stdout only, never in
# argv: the arguments are operation names, IDs, a field path or the expiry.
#   pairs          nebius payload JSON on stdin -> key\0value\0 ...
#   check-payload  exit 0 if a payload JSON on stdin parses (no output); 4 if it has entries
#   pick-secret    the S3 secret of a reference payload on stdin (one entry, or the "secret" one)
#   keys           the entry keys of a payload JSON on stdin, one per line
#   names          the keys of key\0value\0 ... on stdin, one per line
#   digest         sha256 of the sorted entries of a payload JSON on stdin
#   digest-pairs   the same digest for key\0value\0 ... on stdin
#   request ID     key\0value\0 ... on stdin -> the secret-version create request
#   field PATH     a string at a dotted path of the JSON on stdin (non-secret Terraform outputs)
#   check-key SA   an authorized key JSON on stdin is for SA (RS256, iss == sub == SA, as the
#                  SDK requires at startup); prints its kid (not a secret)
#   check-expiry T T is a UTC timestamp at least 30 days ahead
#   token          a new random 64-hex-character token
py() {
  "$PY" -I -c '
import datetime, hashlib, json, secrets, sys

sys.stdout.reconfigure(newline="\n")  # LF line ends everywhere (Python on Windows too)

def entries(node, other):
    if isinstance(node, dict):
        if isinstance(node.get("key"), str) and isinstance(node.get("string_value"), str):
            yield node["key"], node["string_value"]
        elif isinstance(node.get("key"), str) and "binary_value" in node:
            other.append(node["key"])
        else:
            for value in node.values():
                yield from entries(value, other)
    elif isinstance(node, list):
        for value in node:
            yield from entries(value, other)

def from_pairs():
    raw = sys.stdin.buffer.read().decode("utf-8").split("\0")[:-1]
    return list(zip(raw[::2], raw[1::2]))

def digest(found):
    return hashlib.sha256(json.dumps(sorted(found)).encode("utf-8")).hexdigest()

op, args = sys.argv[1], sys.argv[2:]
if op == "token":
    print(secrets.token_hex(32))
elif op == "check-expiry":
    when = datetime.datetime.strptime(args[0], "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=datetime.timezone.utc)
    if when < datetime.datetime.now(datetime.timezone.utc) + datetime.timedelta(days=30):
        sys.exit(1)
elif op == "request":
    payload = [{"key": k, "string_value": v} for k, v in from_pairs()]
    request = {"metadata": {"parent_id": args[0]}, "spec": {"payload": payload, "set_primary": True}}
    sys.stdout.write(json.dumps(request))
elif op == "names":
    print("\n".join(sorted(k for k, _ in from_pairs())))
elif op == "digest-pairs":
    print(digest(from_pairs()))
elif op == "field":
    node = json.load(sys.stdin)
    for part in args[0].split("."):
        node = node.get(part) if isinstance(node, dict) else None
    if not isinstance(node, str) or not node:
        sys.exit(1)
    print(node)
elif op == "check-key":
    try:
        creds = json.load(sys.stdin)["subject-credentials"]
        # what the Nebius SDK checks when it loads the file at startup (credentials_file.py)
        ok = bool(creds["private-key"]) and bool(creds["kid"])
        ok = ok and creds.get("alg") == "RS256" and creds.get("type", "") in ("", "JWT")
        ok = ok and creds.get("iss") == args[0] and creds.get("sub") == args[0]
    except (ValueError, KeyError, TypeError):
        ok = False
    if not ok:
        sys.exit(1)
    print(creds["kid"])
else:
    other = []
    try:
        found = list(entries(json.load(sys.stdin), other))
    except ValueError:
        print("the CLI did not return JSON", file=sys.stderr)
        sys.exit(2)
    if op == "check-payload":
        sys.exit(4 if found or other else 0)
    if other:
        print("entries that are not text (binary_value): " + ", ".join(sorted(other)), file=sys.stderr)
        sys.exit(2)
    if op == "pairs":
        sys.stdout.write("".join(f"{k}\0{v}\0" for k, v in found))
    elif op == "keys":
        print("\n".join(sorted(k for k, _ in found)))
    elif op == "digest":
        print(digest(found))
    elif op == "pick-secret":
        chosen = found if len(found) == 1 else [e for e in found if "secret" in e[0].lower()]
        if len(chosen) != 1 or not chosen[0][1]:
            names = ", ".join(sorted(k for k, _ in found)) or "none"
            print(f"cannot tell which entry is the S3 secret, or it is empty (keys: {names})",
                  file=sys.stderr)
            sys.exit(3)
        sys.stdout.write(chosen[0][1])
' "$@"
}

# --- every input is checked before anything is read from Nebius ----------------------------
only=()
replace_all=0
case "${1:-}" in
  --only)
    [ -n "${2:-}" ] || die "--only needs KEY[,KEY...]"
    IFS=, read -r -a only <<<"$2"
    shift 2
    ;;
  --replace-all) replace_all=1; shift ;;
esac
[ $# -eq 0 ] || die "usage: deploy/secrets.sh [--only KEY[,KEY...] | --replace-all]"
for key in "${only[@]}"; do
  is_key "$key" || die "--only $key: not a key of p2p-secrets (${KEYS[*]} ${OPTIONAL[*]})"
done
command -v "$PY" > /dev/null || die "$PY is needed (set PY to a Python 3 interpreter)"
command -v nebius > /dev/null || die "the nebius CLI is needed (logged in as a tenant admin)"
command -v "$TERRAFORM" > /dev/null || die "$TERRAFORM is needed (the Terraform outputs)"
[[ "$EXPIRES" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z$ ]] \
  || die "P2P_KEY_EXPIRES_AT must look like 2027-01-31T00:00:00Z"

# Which keys get a new value. An S3 key pair changes as a whole.
declare -A wanted=()
if [ "${#only[@]}" = 0 ]; then
  for key in "${KEYS[@]}"; do wanted[$key]=1; done
else
  for key in "${only[@]}"; do wanted[$key]=1; done
  for pair in RUNTIME_S3 JOB_LAUNCHER_S3; do
    if [ -n "${wanted[${pair}_KEY_ID]:-}${wanted[${pair}_SECRET]:-}" ]; then
      wanted[${pair}_KEY_ID]=1 wanted[${pair}_SECRET]=1
    fi
  done
fi
want() { [ -n "${wanted[$1]:-}" ]; }
if want RUNTIME_AUTH_KEY || want JOB_LAUNCHER_AUTH_KEY; then
  py check-expiry "$EXPIRES" || die "P2P_KEY_EXPIRES_AT ($EXPIRES) must be at least 30 days ahead"
fi

tf_out() { "$TERRAFORM" -chdir="$ENVS/$1" output "${@:2}"; }
secret_id=$(tf_out prod -raw secrets_id) || die "terraform output secrets_id (envs/prod) failed $TF_HINT"
[[ "$secret_id" =~ ^[a-z0-9-]+$ ]] || die "secrets_id (envs/prod) is not a SecretStash ID"
declare -A ref=() key_id=() sa=() project=()
if want RUNTIME_S3_SECRET || want JOB_LAUNCHER_S3_SECRET; then
  s3=$(tf_out prod-iam -json s3_access_keys) || die "terraform output s3_access_keys failed $TF_HINT"
  for role in api_runtime job_launcher; do
    key_id[$role]=$(py field "$role.key_id" <<<"$s3") \
      || die "s3_access_keys.$role.key_id is missing (envs/prod-iam)"
    ref[$role]=$(py field "$role.secret_reference_id" <<<"$s3") \
      || die "s3_access_keys.$role.secret_reference_id is missing (envs/prod-iam)"
    [[ "${key_id[$role]}" =~ ^[A-Za-z0-9._-]+$ && "${ref[$role]}" =~ ^[a-z0-9-]+$ ]] \
      || die "s3_access_keys.$role does not look like a key ID and a SecretStash reference"
  done
fi
if want RUNTIME_AUTH_KEY || want JOB_LAUNCHER_AUTH_KEY; then
  sas=$(tf_out prod-iam -json service_account_ids) || die "terraform output service_account_ids failed $TF_HINT"
  env=$(tf_out prod -json env) || die "terraform output env (envs/prod) failed $TF_HINT"
  for role in api_runtime job_launcher; do
    sa[$role]=$(py field "$role" <<<"$sas") || die "service_account_ids.$role is missing"
    [[ "${sa[$role]}" =~ ^[a-z0-9-]+$ ]] || die "service_account_ids.$role is not an ID"
  done
  project[api_runtime]=$(py field NEBIUS_CONTROL_PROJECT_ID <<<"$env") || die "env.NEBIUS_CONTROL_PROJECT_ID is missing"
  project[job_launcher]=$(py field NEBIUS_SANDBOX_PROJECT_ID <<<"$env") || die "env.NEBIUS_SANDBOX_PROJECT_ID is missing"
  for role in api_runtime job_launcher; do
    [[ "${project[$role]}" =~ ^[a-z0-9-]+$ ]] || die "the project of $role is not an ID"
  done
fi

# --- the current version ---------------------------------------------------------------------
declare -A value=()
if [ "${#only[@]}" -gt 0 ]; then
  current=$(nebius mysterybox payload get --secret-id "$secret_id" --format json) \
    || die "cannot read the current version of $secret_id: --only needs one (see the CLI message)"
  py keys <<<"$current" > /dev/null || die "cannot parse the current version of $secret_id"
  while IFS= read -r -d '' k && IFS= read -r -d '' v; do
    is_key "$k" || die "the current version has an unknown key $k: fix it by hand, it would be dropped"
    value[$k]="$v"
  done < <(py pairs <<<"$current")
  unset current
  for key in "${KEYS[@]}"; do
    [ -n "${value[$key]:-}" ] || want "$key" \
      || die "the current version has no $key: run --only with it too, or --replace-all"
  done
elif [ "$replace_all" = 0 ]; then
  # A first load twice would leave two unused authorized keys and reset every session.
  # Only "no version yet" may mean a first load: any other error stops (it is retried, and a
  # retry is how a double load would happen).
  errors=$(mktemp)
  trap 'rm -f "$errors"' EXIT
  if current=$(nebius mysterybox payload get --secret-id "$secret_id" --format json 2> "$errors"); then
    rm -f "$errors"
    status=0
    py check-payload <<<"$current" || status=$?
    unset current
    [ "$status" != 4 ] || die "$secret_id already has a version: use --only KEY,... (rotation) or --replace-all"
    [ "$status" = 0 ] || die "cannot parse the current state of $secret_id (or use --replace-all)"
  else
    message=$(head -c 500 "$errors")
    rm -f "$errors"
    shopt -s nocasematch
    [[ "$message" =~ not.?found|no.primary ]] \
      || die "cannot tell whether $secret_id already has a version: $message (or use --replace-all)"
    shopt -u nocasematch
  fi
fi

# --- the values typed by the human -----------------------------------------------------------
ask() { # ask NAME PROMPT [optional]: hidden input into value[NAME]
  local answer
  printf '%s: ' "$2" >&2
  IFS= read -r -s answer || answer=""
  echo >&2
  answer="${answer%$'\r'}"
  if [ -z "$answer" ]; then
    [ "${3:-}" = optional ] || die "$1 is required"
    return 0
  fi
  [[ "$answer" =~ ^[[:graph:]]+$ ]] || die "$1 must be printable characters only (no spaces)"
  value[$1]="$answer"
}
# A generated token goes to a terminal only, never to a file (P2P_TTY_IS_FILE=1 is for the tests).
can_show() { { [ -c "$TTY" ] || [ "${P2P_TTY_IS_FILE:-}" = 1 ]; } && ( : > "$TTY" ) 2> /dev/null; }
want NEBIUS_API_KEY && ask NEBIUS_API_KEY "NEBIUS_API_KEY (Token Factory API key)"
want TAVILY_API_KEY && ask TAVILY_API_KEY "TAVILY_API_KEY (tvly-...)"
generated_admin=0
if want ADMIN_TOKEN; then
  unset 'value[ADMIN_TOKEN]'
  ask ADMIN_TOKEN "ADMIN_TOKEN (paste one from your password manager; Enter generates one)" optional
  if [ -z "${value[ADMIN_TOKEN]:-}" ]; then
    can_show || die "no terminal to show a generated ADMIN_TOKEN: generate one in your password manager and paste it"
    value[ADMIN_TOKEN]=$(py token)
    generated_admin=1
  fi
  [ "${#value[ADMIN_TOKEN]}" -ge 32 ] || die "ADMIN_TOKEN must have at least 32 characters"
fi
if [ "${#only[@]}" = 0 ] || want OBSERVABILITY_STATIC_KEY; then
  unset 'value[OBSERVABILITY_STATIC_KEY]'
  ask OBSERVABILITY_STATIC_KEY "OBSERVABILITY_STATIC_KEY (only with Nebius Tracing; Enter to skip)" \
    "$([ "${#only[@]}" = 0 ] && echo optional)"
fi
# deploy/endpoint.sh maps the observability key only when prod.env sends traces to Nebius.
if [ -z "${value[OBSERVABILITY_STATIC_KEY]:-}" ] && [ -f "$ENV_FILE" ] \
    && grep -qE '^P2P_TRACES_ENDPOINT=https://write\.tracing\.' "$ENV_FILE"; then
  die "$ENV_FILE sends traces to Nebius Tracing: OBSERVABILITY_STATIC_KEY is required"
fi
want SESSION_KEY && value[SESSION_KEY]=$(py token)
if [ -n "${value[SESSION_KEY]:-}" ] && [ "${value[SESSION_KEY]}" = "${value[ADMIN_TOKEN]:-}" ]; then
  die "SESSION_KEY and ADMIN_TOKEN must differ"
fi

# --- S3 secrets from their references (read only) ---------------------------------------------
for pair in RUNTIME_S3:api_runtime JOB_LAUNCHER_S3:job_launcher; do
  prefix="${pair%%:*}" role="${pair#*:}"
  want "${prefix}_SECRET" || continue
  value[${prefix}_KEY_ID]="${key_id[$role]}"
  reference=$(nebius mysterybox payload get --secret-id "${ref[$role]}" --format json) \
    || die "cannot read the S3 secret of $role (SecretStash ${ref[$role]})"
  value[${prefix}_SECRET]=$(py pick-secret <<<"$reference") \
    || die "the S3 secret of $role: see the message above"
  unset reference
done

# Every required key has a value now, except the authorized keys generated after the confirmation.
for key in "${KEYS[@]}"; do
  case "$key" in RUNTIME_AUTH_KEY | JOB_LAUNCHER_AUTH_KEY) want "$key" && continue ;; esac
  [ -n "${value[$key]:-}" ] || die "$key has no value: nothing changed"
done

# --- the plan, then the confirmation ------------------------------------------------------------
new_keys=()
for key in "${KEYS[@]}" "${OPTIONAL[@]}"; do
  if want "$key"; then
    new_keys+=("$key")
  elif [ "$key" = OBSERVABILITY_STATIC_KEY ] && [ "${#only[@]}" = 0 ] && [ -n "${value[$key]:-}" ]; then
    new_keys+=("$key")
  fi
done
say "a new primary version of $secret_id with new values for: ${new_keys[*]}"
[ "${#only[@]}" = 0 ] || say "kept from the current version: every other key"
for pair in RUNTIME_AUTH_KEY:api_runtime JOB_LAUNCHER_AUTH_KEY:job_launcher; do
  want "${pair%%:*}" || continue
  role="${pair#*:}"
  say "a new authorized key for ${sa[$role]} (in ${project[$role]}), expiring $EXPIRES: this cannot be undone, only deleted"
done
if dry; then
  say "DRY-RUN: no authorized key generated, nothing written"
  exit 0
fi
printf "type 'load' to write it: " >&2
IFS= read -r confirm || confirm=""
[ "${confirm%$'\r'}" = load ] || die "stopped, nothing changed"

# --- new authorized keys (these are real changes in IAM) ---------------------------------------
work=""
if [ -d /dev/shm ]; then work=$(mktemp -d -p /dev/shm 2> /dev/null) || work=""; fi
[ -n "$work" ] || work=$(mktemp -d)
chmod 700 "$work"
generated=()
written=0 # 0: nothing written; 1: written; 2: the write failed, and may still have landed
finish() {
  rm -rf "$work"
  if [ "$written" = 1 ] || [ "${#generated[@]}" = 0 ]; then return 0; fi
  if [ "$written" = 2 ]; then
    echo "secrets.sh: unless nebius mysterybox payload get --secret-id $secret_id shows a new" \
      "version holding them, delete these new authorized keys: ${generated[*]}" >&2
  else
    echo "secrets.sh: these new authorized keys are not in use, delete them: ${generated[*]}" >&2
  fi
  echo "secrets.sh: (nebius iam auth-public-key list --parent-id <that project>, then delete --id)" >&2
}
trap finish EXIT
trap 'exit 130' INT TERM HUP
for pair in RUNTIME_AUTH_KEY:api_runtime JOB_LAUNCHER_AUTH_KEY:job_launcher; do
  key="${pair%%:*}" role="${pair#*:}"
  want "$key" || continue
  file="$work/$role.json"
  (umask 077 && nebius iam auth-public-key generate --parent-id "${project[$role]}" \
    --service-account-id "${sa[$role]}" --output "$file" --output-format service-account-json \
    --expires-at "$EXPIRES" > /dev/null) \
    || die "could not generate an authorized key for ${sa[$role]} (it may exist anyway: nebius iam auth-public-key list --parent-id ${project[$role]})"
  generated+=("${sa[$role]}@${project[$role]}")
  value[$key]=$(cat "$file")
  rm -f "$file"
  kid=$(py check-key "${sa[$role]}" <<<"${value[$key]}") \
    || die "the authorized key file of ${sa[$role]} is not the expected credentials JSON"
  generated[${#generated[@]}-1]="${sa[$role]}@${project[$role]} (kid $kid)"
done

# --- write, then read back ----------------------------------------------------------------------
payload_pairs() {
  local key
  for key in "${KEYS[@]}" "${OPTIONAL[@]}"; do
    [ -n "${value[$key]:-}" ] && printf '%s\0%s\0' "$key" "${value[$key]}"
  done
  return 0
}
request="$work/request.json"
(umask 077 && payload_pairs | py request "$secret_id" > "$request") \
  || die "could not build the request: nothing changed"
# Shown before the write: if the write fails yet lands anyway, the token is still known.
if [ "$generated_admin" = 1 ]; then
  {
    echo
    echo "== the new ADMIN_TOKEN (shown only now: save it in your password manager, then run 'clear'):"
    printf '%s\n' "${value[ADMIN_TOKEN]}"
    printf 'press Enter once it is saved: '
  } > "$TTY"
  IFS= read -r _ || true
fi
if ! nebius mysterybox secret-version create --file "$request" > /dev/null; then
  written=2
  die "writing the new version of $secret_id failed (check with: nebius mysterybox payload get --secret-id $secret_id)"
fi
rm -f "$request"
written=1
expected=$(payload_pairs | py names)
want_digest=$(payload_pairs | py digest-pairs)
back=$(nebius mysterybox payload get --secret-id "$secret_id" --format json) \
  || die "could not read back $secret_id"
got=$(py keys <<<"$back")
got_digest=$(py digest <<<"$back")
unset back
[ "$got" = "$expected" ] && [ "$got_digest" = "$want_digest" ] \
  || die "the new version did not read back with the expected keys and values"
say "p2p-secrets now holds: $(tr '\n' ' ' <<<"$got")"
for entry in "${generated[@]}"; do say "new authorized key: $entry, expiring $EXPIRES"; done

cat << EOF

Next:
  - ADMIN_TOKEN is also the GitHub secret P2P_ADMIN_TOKEN (environment prod):
      gh secret set P2P_ADMIN_TOKEN --env prod     (it asks for the value; paste it)
  - The endpoint reads the secret when it starts: redeploy (deploy/endpoint.sh) to use it.
  - H-04 "done when": terraform plan -detailed-exitcode in envs/prod-iam and envs/prod.
  - When you are done: unset AWS_ACCESS_KEY_ID AWS_SECRET_ACCESS_KEY NEBIUS_IAM_TOKEN
  - After a rotation of *_AUTH_KEY, delete the old authorized keys once the redeploy works,
    and the old versions of p2p-secrets (they still hold the old values).
EOF
